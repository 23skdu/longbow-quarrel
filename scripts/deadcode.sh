#!/usr/bin/env bash
# =============================================================================
# scripts/deadcode.sh - the dead code gate
# =============================================================================
#
# The rule this repository has always followed is "wire it or delete it": a
# function that no code path reaches is a subsystem a reader would
# reasonably believe is live. This gate finds those functions and fails
# when a new one appears.
#
# The analysis is golang.org/x/tools/cmd/deadcode over the whole module:
# it starts from the main packages, follows every call it can see, and
# reports the functions nothing reaches.
#
# The test files are roots too: a helper that only the tests call is not
# dead code, it is a test oracle. That is why the analysis runs with
# -test. Without it the report is the ~250 functions of the 2026-09
# audit, most of which the tests keep alive.
#
# The known offenders live in scripts/deadcode_allowlist.txt. Every entry
# is debt: delete the code, or delete its line from the allowlist.
#
# Usage:
#   scripts/deadcode.sh            check against the allowlist
#   scripts/deadcode.sh --update   rewrite the allowlist
# =============================================================================
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

ALLOWLIST="scripts/deadcode_allowlist.txt"
DEADCODE_VERSION="v0.52.0"
UPDATE=0

if [ "${1:-}" = "--update" ]; then
	UPDATE=1
fi

if ! command -v go >/dev/null 2>&1; then
	echo "deadcode: go is not on the path" >&2
	exit 1
fi

# The tool is pinned so that the gate reports the same thing on every host.
DEADCODE=(go run "golang.org/x/tools/cmd/deadcode@${DEADCODE_VERSION}")

echo "=== Dead code gate ==="

if ! output="$("${DEADCODE[@]}" -test ./... 2>/dev/null)"; then
	echo "deadcode: the module could not be analysed" >&2
	exit 1
fi

# The line and column numbers are dropped: an edit above a dead function
# moves them, and the gate is about the function, not about where it is.
normalize() {
	sed -E 's|^([^:]*):[0-9]+:[0-9]+: |\1: |'
}

found="$(printf '%s\n' "$output" | grep 'unreachable func' | normalize || true)"

if [ -z "$found" ]; then
	echo "deadcode: OK - nothing is unreachable"
	if [ "$UPDATE" = "1" ]; then
		{
			echo "# Functions that no code path reaches. Every entry is debt:"
			echo "# wire the code, delete it, or delete its line here."
			echo "# Generated by: scripts/deadcode.sh --update"
		} >"$ALLOWLIST"
	fi
	exit 0
fi

count="$(printf '%s\n' "$found" | grep -c 'unreachable func' || true)"
echo "deadcode: $count unreachable functions"

if [ "$UPDATE" = "1" ]; then
	{
		echo "# Functions that no code path reaches. Every entry is debt:"
		echo "# wire the code, delete it, or delete its line here."
		echo "# A trailing comment says why the entry is still there."
		echo "# Generated by: scripts/deadcode.sh --update"
		printf '%s\n' "$found" | sort -u
	} >"$ALLOWLIST"
	echo "deadcode: rewrote $ALLOWLIST"
	exit 0
fi

if [ ! -f "$ALLOWLIST" ]; then
	echo "deadcode: $ALLOWLIST does not exist; run scripts/deadcode.sh --update" >&2
	printf '%s\n' "$found" >&2
	exit 1
fi

allowed="$(grep -v '^#' "$ALLOWLIST" | sed '/^$/d' | sed 's/[[:space:]]*#.*$//' | sed 's/[[:space:]]*$//' | normalize | sort -u)"

# The functions that are not on the list are new debt.
new="$(printf '%s\n' "$found" | sort -u | comm -13 <(printf '%s\n' "$allowed") - || true)"

# The entries that no longer apply are debt in the other direction: the
# allowlist has to shrink.
stale="$(comm -23 <(printf '%s\n' "$allowed") <(printf '%s\n' "$found" | sort -u) || true)"

status=0

if [ -n "$new" ]; then
	echo "deadcode: FAIL - new unreachable functions:" >&2
	printf '%s\n' "$new" >&2
	status=1
fi

if [ -n "$stale" ]; then
	echo "deadcode: these allowlist entries no longer apply (remove them):" >&2
	printf '%s\n' "$stale" >&2
	status=1
fi

if [ "$status" = "0" ]; then
	echo "deadcode: OK - the unreachable set matches the allowlist"
fi

exit "$status"
